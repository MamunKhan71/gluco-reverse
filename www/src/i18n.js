const DICTS = { bn, en };
let lang = 'bn';

export function setLang(l) {
  lang = DICTS[l] ? l : 'bn';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function tIn(lang, key, ...args) {
  const v = (DICTS[lang] ?? DICTS.bn)[key] ?? DICTS.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : Array.isArray(v) ? [...v] : v;
}

export function t(key, ...args) {
  const v = DICTS[lang][key] ?? DICTS.en[key] ?? (key.startsWith('ins_') ? key.slice(4) : key);
  return typeof v === 'function' ? v(...args) : v;
}
