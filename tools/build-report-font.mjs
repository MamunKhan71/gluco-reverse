// Bundles Space Grotesk (SIL Open Font License) into www/src/reportfont.js as base64 @font-face
// rules, so the printed report looks the same with or without internet.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'node_modules/@fontsource/space-grotesk/files';
const faces = [400, 500, 700]
  .map((w) => {
    const b64 = readFileSync(`${dir}/space-grotesk-latin-${w}-normal.woff2`).toString('base64');
    return `@font-face{font-family:'Space Grotesk';font-style:normal;font-weight:${w};src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
  })
  .join('');
writeFileSync('www/src/reportfont.js', `// Generated by tools/build-report-font.mjs (Space Grotesk, SIL Open Font License 1.1).\nexport const REPORT_FONT_CSS = ${JSON.stringify(faces)};\n`);
console.log('reportfont.js', faces.length, 'chars');
