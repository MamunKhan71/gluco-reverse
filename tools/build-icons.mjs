const out = {};
for (const [name, candidates] of Object.entries(MAP)) {
  const hit = candidates.find((c) => existsSync(new URL(`${c}.svg`, DIR)));
  if (!hit) throw new Error(`No Lucide icon for ${name}: ${candidates}`);
  const svg = readFileSync(new URL(`${hit}.svg`, DIR), 'utf8');
  out[name] = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '');
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: '${v}',`)
  .join('\n');

writeFileSync(
  new URL('../www/src/icons.js', import.meta.url),
  `// Generated by tools/build-icons.mjs from Lucide (https://lucide.dev, ISC licence). Do not edit by hand.
const P = {
${body}
};

export function icon(name, cls = '') {
  return \`<svg class="ic \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${P[name] ?? ''}</svg>\`;
}

export const SLOT_ICON = { breakfast: 'sunrise', lunch: 'sun', snack: 'cup', dinner: 'sunset', night: 'moon' };
`,
);
